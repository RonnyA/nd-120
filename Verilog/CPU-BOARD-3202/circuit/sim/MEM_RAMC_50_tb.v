    dir_in[ 74] = 10'h2FF; dir_out[ 74] = 11'h335;
  end

  // one OSC cycle: inputs set at negedge, PALs clock at posedge, sample #1
  task do_cycle;
    begin
      @(negedge osc);
      rlrq_n    = iw[0];
      clrq_n    = iw[1];
      blrq50_n  = iw[2];
      ssema_n   = iw[3];
      semrq50_n = iw[4];
      mr_n      = iw[5];
      bdap50_n  = iw[6];
      bdry50_n  = iw[7];
      bgnt25_n  = iw[8];
      cgnt25_n  = iw[9];
      @(posedge osc);
      #1;
    end
  endtask

  always #5 osc = ~osc;

  initial begin
    // Deposit all-zero PAL state (registers have no initializer; the
    // Python model starts from the same all-zero state).
    dut.PAL_44803_URAMA.RGNT_reg = 0;
    dut.PAL_44803_URAMA.CGNT_reg = 0;
    dut.PAL_44803_URAMA.BGNT_reg = 0;
    dut.PAL_44803_URAMA.LDR_reg = 0;
    dut.PAL_44803_URAMA.CSEM_reg = 0;
    dut.PAL_44803_URAMA.BSEM_reg = 0;
    dut.PAL_44803_URAMA.LOEN25_reg = 0;
    dut.PAL_44803_URAMA.BCGNT25_n_reg = 0;
    dut.PAL_44902_URAMC.QA_reg = 0;
    dut.PAL_44902_URAMC.QB_reg = 0;
    dut.PAL_44902_URAMC.QC_reg = 0;
    dut.PAL_44902_URAMC.QD_reg = 0;
    dut.PAL_44902_URAMC.RAS_n_reg = 0;
    dut.PAL_44902_URAMC.CAS_n_reg = 0;
    dut.PAL_44902_URAMC.LOEN_reg = 0;
    dut.PAL_44902_URAMC.HIEN_reg = 0;

    // ---- 1. directed phase ----
    for (k = 0; k < 75; k = k + 1) begin
      iw = dir_in[k];
      do_cycle;
      checks = checks + 1;
      if (outword !== dir_out[k]) begin
        errors = errors + 1;
        $display("FAIL dir[%0d]: in=%03h got out=%03h expected %03h",
                 k, iw, outword, dir_out[k]);
      end
    end

    // ---- 2. LFSR phase ----
    for (k = 0; k < 2000; k = k + 1) begin
      lfsr = (lfsr >> 1) ^ (lfsr[0] ? 32'hEDB88320 : 32'h0);
      b = lfsr;
      iw = {b[8], b[7], b[6], b[5],
            (b[11:9] == 3'b000) ? 1'b0 : 1'b1,
            b[4], b[3], b[2], b[1], b[0]};
      do_cycle;
      // one-hot grant invariant
      grants = (rgnt_n ? 0 : 1) + (cgnt_n ? 0 : 1) + (bgnt_n ? 0 : 1);
      checks = checks + 1;
      if (grants > 1) begin
        errors = errors + 1;
        $display("FAIL invariant cycle %0d: %0d grants asserted", k, grants);
      end
      acc = (acc << 5) - acc + {21'b0, outword};
    end

    checks = checks + 1;
    if (acc !== 32'h1CE85BBA) begin
      errors = errors + 1;
      $display("FAIL checksum: got %08h expected 1CE85BBA", acc);
    end

    // ---- 3. PD tri-state comb checks (no clock) ----
    pd1 = 1;
    #2;
    checks = checks + 1;
    if ({rgnt_n, cgnt_n, bgnt_n, bcgnt25} !== 4'b0000) begin
      errors = errors + 1;
      $display("FAIL PD1: grant pins not forced 0: %b",
               {rgnt_n, cgnt_n, bgnt_n, bcgnt25});
    end
    pd3 = 1;
    #2;
    checks = checks + 1;
    if ({qd_n, ras, cas, loen_n, hien_n} !== 5'b00000) begin
      errors = errors + 1;
      $display("FAIL PD3: strobe pins not forced 0: %b",
               {qd_n, ras, cas, loen_n, hien_n});
    end

    // Verdict. Expected: 75 + 2000 + 1 + 2 = 2078.
    if (errors == 0 && checks == 2078)
      $display("TB_RESULT: PASS (%0d checks)", checks);
    else
      $display("TB_RESULT: FAIL (%0d errors, %0d of 2078 checks)",
               errors, checks);
    $finish;
  end

endmodule
