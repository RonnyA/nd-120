/**************************************************************************
** ND120 CPU - unit test                                                 **
** MEM_RAMC_50: local RAM control sheet (sheet 50) - PAL_44803A RAM      **
** arbiter (5F) cross-coupled with the PAL_44902A RAM-control state      **
** machine (6F), both clocked by OSC.                                    **
**                                                                       **
** Golden behavior comes from the INDEPENDENT Python model               **
** gen_ramc_golden.py (scratchpad, not in repo), which re-transcribes    **
** the two PALs' registered equations plus the sheet cross-wiring        **
** (44803A.LOEN_n <- 44902A LOEN_n pin, 44902A.RGNT_n <- 44803A RGNT_n   **
** pin) and emits the embedded tables/constants below.                   **
**                                                                       **
**  1. Directed phase (75 cycles, per-cycle full 11-output compare):     **
**     reset, CPU grant walk, bus grant walk, refresh priority, the      **
**     LDR "CPU after last-done-refresh" path, and the CSEM semaphore    **
**     hold. CGNT25_n/BGNT25_n are driven as 1-OSC-delayed copies of     **
**     the DUT's own CGNT_n/BGNT_n (board behavior on sheet 48).         **
**  2. LFSR phase (2000 cycles, fixed seed ACE1ACE1): random inputs      **
**     (MR_n low 1/8 of the time); per cycle the one-hot grant           **
**     invariant is asserted and all 11 outputs are folded into a        **
**     running checksum acc = acc*31 + out, compared at the end.         **
**  3. PD comb checks: PD1=1 forces the 44803A grant pins to 0, PD3=1    **
**     forces the 44902A strobe pins to 0 (FPGA no-Z convention).        **
**                                                                       **
** The PAL registers have no initializer, so the tb DEPOSITS 0 into all  **
** 16 state registers at t0 (hierarchical refs, sim-only); the Python    **
** model starts from the same all-zero state.                            **
**                                                                       **
** No ifdef build split applies (no VERILATOR_SIM / FPGA_FF_MODE /       **
** USE_TRANSPARENT_LATCHES branch in the DUT or in these two PALs) -     **
** single iverilog build, posedge-CK PAL semantics as on the FPGA and    **
** in Verilator.                                                         **
**                                                                       **
** Self-checking: prints TB_RESULT: PASS / FAIL (never silent).          **
**                                                                       **
** Run: make test-ramc   (CPU-BOARD-3202/circuit/sim)                    **
**                                                                       **
** 31-JUL-2026                                                           **
** Ronny Hansen                                                          **
***************************************************************************/
`timescale 1ns / 1ps

module MEM_RAMC_50_tb;

  // osc starts HIGH so the first posedge comes only after the first
  // do_cycle input setup (no stray clock before the directed phase).
  reg osc = 1;

  reg bdap50_n = 1;
  reg bdry50_n = 1;
  reg bgnt25_n = 1;
  reg blrq50_n = 1;
  reg cgnt25_n = 1;
  reg clrq_n = 1;
  reg mr_n = 1;
  reg pd1 = 0;
  reg pd3 = 0;
  reg rlrq_n = 1;
  reg semrq50_n = 1;
  reg ssema_n = 1;

  wire bcgnt25, bgnt_n, ras, cas, cgnt_n, hien_n, loen_n, qd_n, rgnt_n;
  wire led_cpu_gi, led_bus_gi;

  MEM_RAMC_50 dut (
      .BDAP50_n (bdap50_n),
      .BDRY50_n (bdry50_n),
      .BGNT25_n (bgnt25_n),
      .BLRQ50_n (blrq50_n),
